        with open("env.schema.toml", "w") as f:
            f.write('[DB_HOST]\ndescription="x"\n\n[FEATURE_MODE]\ndescription="x"\n')
        with open("config/settings.py", "w") as f:
            f.write('DB_HOST = "localhost"\n')
